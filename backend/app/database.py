# Predefined admin accounts, created only when there are none yet.
# Change these passwords (or add people) with: uv run python -m app.create_admin
SEED_ADMINS = [
    ("admin", "Store Admin", "admin123"),
    ("manager", "Store Manager", "manager123"),
]


# autocommit: each statement saves at once, and several statements that must
# succeed or fail together go inside "with db.transaction():"
CONNECTION_OPTIONS = {"autocommit": True, "row_factory": dict_row}  # rows behave like dicts: row["name"]

# Reuses open connections between requests instead of opening a new one each time
pool = ConnectionPool(DATABASE_URL, kwargs=CONNECTION_OPTIONS, open=False)


def connect() -> psycopg.Connection:
    """A standalone connection, for scripts like create_admin."""
    return psycopg.connect(DATABASE_URL, **CONNECTION_OPTIONS)


def get_db():
    """FastAPI dependency: one connection per request, given back to the pool afterwards."""
    with pool.connection() as db:
        yield db


def init_db() -> None:
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    with connect() as db, db.transaction():
        db.execute(SCHEMA)
        if not db.execute("SELECT 1 FROM products LIMIT 1").fetchone():
            db.cursor().executemany(
                """INSERT INTO products (id, slug, name, description, category, price,
                                         compare_at_price, stock, image, rating, review_count)
                   VALUES (%(id)s, %(slug)s, %(name)s, %(description)s, %(category)s, %(price)s,
                           %(compare_at_price)s, %(stock)s, '/' || %(slug)s || '.jpg', %(rating)s,
                           %(review_count)s)""",
                SEED_PRODUCTS,
            )
            # The seed rows chose their own ids; new products continue after them
            db.execute("SELECT setval(pg_get_serial_sequence('products', 'id'), MAX(id)) FROM products")
        if not db.execute("SELECT 1 FROM admins LIMIT 1").fetchone():
            db.cursor().executemany(
                "INSERT INTO admins (username, name, password_hash) VALUES (%s, %s, %s)",
                [(u, n, hash_password(p)) for u, n, p in SEED_ADMINS],
            )
